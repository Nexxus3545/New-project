const assert = require('node:assert/strict');
const { test, after } = require('node:test');
const nodemailer = require('nodemailer');
const originalTransport = nodemailer.createTransport;
const originalTestAccount = nodemailer.createTestAccount;
const originalEnv = { ...process.env };
let options;
let rejected = false;
nodemailer.createTestAccount = () => { throw new Error('Production must not create test mailboxes'); };
nodemailer.createTransport = (config) => { options = config; return { sendMail: async () => ({ messageId: 'test-only', accepted: rejected ? [] : ['test@example.invalid'], rejected: rejected ? ['test@example.invalid'] : [] }) }; };
const { sendMail, isEmailConfigured } = require('../src/utils/mailer');
after(() => { nodemailer.createTransport = originalTransport; nodemailer.createTestAccount = originalTestAccount; process.env = originalEnv; });
test('production email refuses test fallback, secures SMTP, and detects recipient rejection', async () => {
  delete process.env.VERCEL_ENV;
  process.env.NODE_ENV = 'production'; process.env.EMAIL_ALLOW_TEST_TRANSPORT = 'true';
  for (const key of ['EMAIL_HOST', 'EMAIL_USER', 'EMAIL_PASS', 'EMAIL_FROM']) delete process.env[key];
  assert.equal(isEmailConfigured(), false);
  await assert.rejects(sendMail({ to: 'test@example.invalid', subject: 'Test', text: 'Test' }), { code: 'EMAIL_NOT_CONFIGURED' });
  Object.assign(process.env, { EMAIL_HOST: 'smtp.example.invalid', EMAIL_USER: 'sender@example.invalid', EMAIL_PASS: 'test-only', EMAIL_FROM: 'Clinic <sender@example.invalid>', EMAIL_PORT: '465' });
  assert.equal(isEmailConfigured(), true);
  assert.equal((await sendMail({ to: 'test@example.invalid', subject: 'Test', text: 'Test' })).accepted, true);
  assert.equal(options.secure, true);
  assert.equal(options.disableFileAccess, true);
  assert.equal(options.disableUrlAccess, true);
  assert.ok(options.socketTimeout <= 5000);
  rejected = true;
  await assert.rejects(sendMail({ to: 'test@example.invalid', subject: 'Test', text: 'Test' }), { code: 'EMAIL_REJECTED' });
  process.env.VERCEL_ENV = 'preview';
  assert.equal(isEmailConfigured(), false, 'Preview deployments cannot send production patient emails');
  await assert.rejects(sendMail({ to: 'test@example.invalid', subject: 'Test', text: 'Test' }), { code: 'EMAIL_NOT_CONFIGURED' });
});
